  row("\\quad Cost growth, ordinary regime ($\\beta_h$)", cf(m$reg_beta, m$reg_beta_se)),
  row("", sef(m$reg_beta_se)),
  row("\\quad Total effect, high-cost regime ($\\beta_h{+}\\theta_h$)", cf(m$reg_b, m$reg_se)),
  row("", sef(m$reg_se)),
  row("\\quad $R^2$", num(m$reg_r2)),
  "\\addlinespace[3pt]",
  sprintf("\\multicolumn{%d}{@{}l}{\\textit{Panel C. IV local projection: average response}}\\\\[1pt]", nc + 1),
  row("\\quad Construction cost growth $c_t$", cf(v$iva_b, v$iva_se)),
  row("", sef(v$iva_se)),
  row("\\quad First-stage $F$ (DK)", num(v$iva_F, 1)),
  row("\\quad AR 95\\% set, lower bound", arcell(a$ar_lo)),
  row("\\quad AR 95\\% set, upper bound", arcell(a$ar_hi)),
  "\\addlinespace[3pt]",
  sprintf("\\multicolumn{%d}{@{}l}{\\textit{Panel D. IV local projection: high-cost regime}}\\\\[1pt]", nc + 1),
