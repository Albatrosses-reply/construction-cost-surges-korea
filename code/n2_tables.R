  row(sprintf("\\quad Lags 1--%d of housing-market controls", P), rep("Yes", nc)),
  row(sprintf("\\quad Lags 1--%d of macroeconomic controls", P), rep("Yes", nc)),
  row(sprintf("\\quad Lags 1--%d of instruments (Panels C--D)", P), rep("Yes", nc)),
  row("\\quad Observations", comma(m$avg_n)),
