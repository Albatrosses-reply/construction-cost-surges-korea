                    reg_b = m$reg_b, reg_se = m$reg_se, reg_r2 = m$reg_r2, iva_b = v$iva_b, iva_se = v$iva_se, iva_F = v$iva_F,
                    ar_lo = a$ar_lo, ar_hi = a$ar_hi, ivr_b = v$ivr_b, ivr_se = v$ivr_se, ivr_F1 = v$ivr_F1, ivr_F2 = v$ivr_F2, n = m$avg_n)

