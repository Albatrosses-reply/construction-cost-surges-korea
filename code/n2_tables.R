args <- commandArgs(trailingOnly = FALSE); f <- sub("--file=", "", args[grep("--file=", args)]); if (length(f)) setwd(dirname(normalizePath(f)))
suppressPackageStartupMessages({library(jsonlite)})
main <- read.csv("out/est_main.csv"); iv <- read.csv("out/est_iv.csv"); ar <- read.csv("out/est_iv_ar.csv")
reg <- read.csv("out/est_region.csv"); rob <- read.csv("out/est_robust.csv"); meta <- fromJSON("out/meta.json")
P <- meta$p_main
pv <- function(b, s) 2 * pnorm(-abs(b / s))
stars <- function(p) ifelse(p < .01, "^{***}", ifelse(p < .05, "^{**}", ifelse(p < .1, "^{*}", "")))
num <- function(x, d = 3) { s <- formatC(x, format = "f", digits = d); s <- sub("^-", "-", s); ifelse(s == paste0("-", formatC(0, format = "f", digits = d)), formatC(0, format = "f", digits = d), s) }
cf  <- function(b, se, extra = "") paste0("$", num(b), stars(pv(b, se)), extra, "$")
sef <- function(se) paste0("$(", num(se), ")$")
comma <- function(n) formatC(n, format = "d", big.mark = "{,}")
row <- function(label, cells) paste0(label, " & ", paste(cells, collapse = " & "), "\\\\")
nums <- list()

# ------------------------------------------------------------------ Table 3
HR <- c(0, 3, 6, 9, 12, 15, 18, 24)
m <- main[match(HR, main$h), ]; v <- iv[match(HR, iv$h), ]; a <- ar[match(HR, ar$h), ]
