# ------------------------------------------------------------------ wrapper with captions and notes
mk <- read.csv("out/markov_probs.csv")
span <- function(v) { w <- mk$Monthly2[v == 1]; sprintf("%s:%d--%s:%d", substr(min(w), 1, 4), as.integer(substr(min(w), 6, 7)), substr(max(w), 1, 4), as.integer(substr(max(w), 6, 7))) }
samp0 <- sprintf("%s:%d", substr(meta$sample[1], 1, 4), as.integer(substr(meta$sample[1], 6, 7)))
samp1 <- sprintf("%s:%d", substr(meta$sample[2], 1, 4), as.integer(substr(meta$sample[2], 6, 7)))
ic <- read.csv("out/d7_ic_table.csv"); p_aic <- which.min(ic$AIC)
star_note <- "\\sym{*}\\,$p<0.10$, \\sym{**}\\,$p<0.05$, \\sym{***}\\,$p<0.01$."
ctrl_note <- sprintf(paste0("All specifications include region fixed effects and lags 1--%d of log housing starts, cost growth, the housing-market controls ",
  "(apartment transaction volume, monthly housing permits, unsold units, registered households, apartment sales price index), and the ",
  "macroeconomic controls (three-year Treasury yield, corporate--Treasury spread, producer price index, KRW/USD exchange rate). ",
  "The lag length is the AIC choice (%d) in a VAR of the national series plus one, following the lag augmentation of Montiel Olea and ",
  "Plagborg-M{\\o}ller (2021)."), P, p_aic)
wrap <- function(file, caption, label, notes, size = "\\scriptsize", sep = "4pt") c(
  "\\begin{table}[p]\\centering\\begin{threeparttable}",
  sprintf("\\caption{%s}\\label{%s}", caption, label),
  sprintf("%s\\setlength{\\tabcolsep}{%s}\\renewcommand{\\arraystretch}{0.88}", size, sep),
  sprintf("\\input{%s}", file),
  "\\begin{tablenotes}[flushleft]\\scriptsize",
  paste0("\\item \\textit{Notes:} ", notes),
  "\\end{tablenotes}\\end{threeparttable}\\end{table}", "\\clearpage")
n3 <- paste(
  sprintf("An observation is a region--month (eight Korean regions; estimation sample %s--%s, shortened by $h$ months at the end).", samp0, samp1),
  "Each column is a separate local projection of the cumulative change in log housing starts from $t-1$ to $t+h$ on year-over-year",
  "construction cost growth $c_t$ (percentage points). Panel B adds the high-cost-regime indicator $D_t$ (Markov-switching smoothed",
  sprintf("probability above 0.5, %s) and $c_t\\times D_t$; $\\beta_h$ is the response in the ordinary regime and $\\beta_h+\\theta_h$ the total", span(mk$D50)),
  "response in the high-cost regime. Panels C--D instrument $c_t$ (and $c_t\\times D_t$) with year-over-year growth of global aluminum,",
  "iron-ore, and copper prices (and their interactions with $D_t$), and also include lags of the instruments.", ctrl_note,
  "Driscoll--Kraay (DK) standard errors with bandwidth $h+1$ in parentheses. First-stage $F$ statistics are Wald tests of the excluded",
  "instruments with the same DK covariance. Anderson--Rubin (AR) sets are obtained by test inversion on a grid (step 0.01 within",
  sprintf("$\\pm1.5$, 0.1 outside). One standard deviation of the cost-growth innovation is %s percentage points.", num(meta$sd_innovation_pp, 2)),
  star_note)
n4 <- paste("Each column is a single pooled local projection augmented with region $\\times$ $c_t$ interactions; Seoul is the reference region.",
  "Each cell is the region-specific total response $\\hat\\beta_h+\\hat\\delta_{r,h}$ (Seoul: $\\hat\\beta_h$) of cumulative log housing starts.",
  sprintf("Controls as in Table 3, with lags 1--%d and coefficients common to all regions.", P),
  "Driscoll--Kraay standard errors (bandwidth $h+1$, delta method) in parentheses.", star_note,
  "$\\dagger$ marks estimates that remain significant at the 10\\% level after a Holm correction across the 40 region--horizon tests.")
n6 <- paste("Each cell is the high-cost-regime total effect $\\hat\\beta_h+\\hat\\theta_h$ from a separate local projection.",
  "Column 1 is the baseline of Table 3, Panel B. Columns 2--3 use two and three lags of all variables.",
  sprintf("Column 4 adds lags 1--%d of $D_t$ and $c_t\\times D_t$.", P),
  "Columns 5--6 reproduce the original specification (one lag of starts and controls, no lags of cost growth, year-to-date cumulative",
  "permits) with month-clustered and Driscoll--Kraay standard errors.",
  sprintf("Column 7 defines the high-cost regime as months in the top decile of cost growth (%s). Columns 8--9 drop Gyeonggi and Daegu.", span(mk$Dtop10)),
  sprintf("A smoothed-probability cutoff of 0.6 selects the same months as the baseline (%s) and is not reported separately.", span(mk$D60)),
  "Standard errors in parentheses.", star_note)
