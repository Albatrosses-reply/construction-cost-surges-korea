# Markov-switching table (Table A.1), estimated with MSwM::msmFit (EM)
#   two regimes, switching mean, common variance, on national YoY construction-cost growth 2011:1-2026:1
#   writes tables/tab_tA1_markov.tex (tabular only) and out/markov_msm.json; compares with n0 (Hamilton filter, BFGS)
args <- commandArgs(trailingOnly = FALSE); f <- sub("--file=", "", args[grep("--file=", args)]); if (length(f)) setwd(dirname(normalizePath(f)))
suppressPackageStartupMessages({library(MSwM); library(jsonlite)})
set.seed(20261004)
d <- read.csv("../data/panel_8_regions.csv", check.names = FALSE)
m <- unique(d[, c("Monthly2", "yoy_CCI", "regime_dummy")]); m <- m[order(m$Monthly2), ]
fit <- msmFit(lm(yoy_CCI ~ 1, data = m), k = 2, sw = c(TRUE, FALSE))
mu <- as.numeric(fit@Coef[, 1]); hi <- which.max(mu); lo <- 3 - hi
P <- fit@transMat                      # P[i, j] = Pr(s_t = i | s_{t-1} = j) in MSwM
pr <- fit@Fit@smoProb; if (nrow(pr) == nrow(m) + 1) pr <- pr[-1, , drop = FALSE]
D <- as.integer(pr[, hi] > 0.5)
w <- m$Monthly2[D == 1]
res <- list(mu_low = mu[lo], mu_high = mu[hi], p_LL = P[lo, lo], p_LH = P[hi, lo], p_HL = P[lo, hi], p_HH = P[hi, hi],
            share_high = mean(D), first = substr(min(w), 1, 7), last = substr(max(w), 1, 7), months = length(w),
            matches_paper_dummy = all(D == m$regime_dummy), loglik = fit@Fit@logLikel)
write_json(res, "out/markov_msm.json", auto_unbox = TRUE, digits = 6, pretty = TRUE)
f3 <- function(x) formatC(x, format = "f", digits = 3)
ym <- function(s) sub("-0?", ":", s)
t <- c("% structure-ok: no-r2 (Markov-switching parameter table); generated by n0b_markov_table.R",
  "\\begin{tabular}{@{}l cc@{}}", "\\toprule",
  "\\multicolumn{3}{@{}l}{\\textit{Panel A. Estimated regime means (cost growth, \\% YoY)}}\\\\[1pt]",
  sprintf("\\quad Low-cost regime & \\multicolumn{2}{c}{%s}\\\\", f3(res$mu_low)),
  sprintf("\\quad High-cost regime & \\multicolumn{2}{c}{%s}\\\\", f3(res$mu_high)),
  "\\addlinespace[3pt]", "\\multicolumn{3}{@{}l}{\\textit{Panel B. Transition probability matrix}}\\\\[1pt]",
  " & To low-cost & To high-cost\\\\", "\\cmidrule(lr){2-3}",
  sprintf("\\quad From low-cost & %s & %s\\\\", f3(res$p_LL), f3(res$p_LH)),
  sprintf("\\quad From high-cost & %s & %s\\\\", f3(res$p_HL), f3(res$p_HH)),
  "\\addlinespace[3pt]", "\\multicolumn{3}{@{}l}{\\textit{Panel C. Classification}}\\\\[1pt]",
  "\\quad Smoothed-probability cutoff & \\multicolumn{2}{c}{0.50}\\\\",
  sprintf("\\quad Share of months in high-cost regime & \\multicolumn{2}{c}{%s\\%%}\\\\", formatC(100 * res$share_high, format = "f", digits = 1)),
  sprintf("\\quad High-cost regime span & \\multicolumn{2}{c}{%s--%s}\\\\", ym(res$first), ym(res$last)),
  sprintf("\\quad Months (2011:1--2026:1) & \\multicolumn{2}{c}{%d}\\\\", nrow(m)),
  "\\bottomrule", "\\end{tabular}")
writeLines(t, "tables/tab_tA1_markov.tex")
str(res)
