# Robustness of the average and regime responses (Table 9), and the response of the cost level (not reported in the paper)
#   tables/tab_t7_robust_avg.tex (Table 9): Panel A average response, Panel B high-cost-regime total effect, four specifications
#     (1) baseline (2) excluding Daegu (3) weighted by each region's mean monthly starts (4) same-month PPI, Treasury yield, spread
#   out/est_robust_avg.csv
#   out/est_cost_level.csv, figures/fig_cost_level_response.png : log CCI response to the cost-growth surprise (national)
args <- commandArgs(trailingOnly = FALSE); f <- sub("--file=", "", args[grep("--file=", args)]); if (length(f)) setwd(dirname(normalizePath(f)))
suppressPackageStartupMessages({library(dplyr); library(fixest); library(ggplot2)})
d0 <- read.csv("../data/panel_8_regions.csv", check.names = FALSE)
d0$date <- as.Date(d0$Monthly2); names(d0) <- gsub("\\.", "_", gsub(" ", "_", names(d0)))
raw <- read.csv("../data/monthly_series_wide.csv", check.names = FALSE)
raw$date <- as.Date(substr(raw$Monthly2, 1, 10)); raw$m <- as.integer(format(raw$date, "%m"))
regs <- c("seoul", "busan", "daegu", "incheon", "gwangju", "daejeon", "ulsan", "gyeonggi")
pm <- bind_rows(lapply(regs, function(g) {
  ytd <- raw[[paste0("permit_pri_", g)]]
  data.frame(date = raw$date, region = g, permit_flow = pmax(ifelse(raw$m == 1, ytd, ytd - dplyr::lag(ytd)), 0))
}))
d0 <- d0 %>% left_join(pm, by = c("date", "region")) %>% mutate(l_permit_flow = log(1 + permit_flow)) %>%
  left_join(raw %>% transmute(date, l_cci = log(CCI)), by = "date")
HX <- c("l_apt_trd", "l_permit_flow", "l_unsold_pri", "l_hh", "l_apt_price_idx")
MX <- c("rate_k3y", "spread_corp3y", "l_ppi", "l_fx_usdkrw")
d0 <- d0 %>% arrange(region, date) %>% group_by(region) %>% mutate(tid = row_number()) %>% ungroup()
for (v in c("l_start_pri", "yoy_CCI", HX, MX, "l_cci")) for (l in 1:4) d0[[paste0(v, "_L", l)]] <- ave(d0[[v]], d0$region, FUN = function(x) dplyr::lag(x, l))
lt <- function(vars) paste(as.vector(outer(vars, 1:4, function(a, b) paste0(a, "_L", b))), collapse = " + ")
base_ctrl <- lt(c("l_start_pri", "yoy_CCI", HX, MX))
d0 <- d0 %>% left_join(d0 %>% group_by(region) %>% summarise(w = mean(exp(l_start_pri) - 1, na.rm = TRUE)), by = "region")
H <- c(0, 3, 6, 9, 12, 15, 18, 24)
fitset <- function(dat, rhs, regime, w = NULL) {
  lapply(H, function(h) {
    dd <- dat %>% group_by(region) %>% mutate(y = dplyr::lead(l_start_pri, h) - l_start_pri_L1) %>% ungroup()
    e <- feols(as.formula(paste("y ~", rhs, "| region")), dd, panel.id = ~ region + tid, vcov = DK(lag = h + 1),
               weights = if (is.null(w)) NULL else as.formula(paste0("~", w)), notes = FALSE, warn = FALSE)
    k <- if (regime) c("yoy_CCI", "yoy_CCI_regime") else "yoy_CCI"
    data.frame(h = h, b = sum(coef(e)[k]), se = sqrt(sum(vcov(e)[k, k])), n = nobs(e), r2 = unname(r2(e, "r2")))
  }) %>% bind_rows()
}
ra <- paste("yoy_CCI +", base_ctrl); rr <- paste("yoy_CCI + regime_dummy + yoy_CCI_regime +", base_ctrl)
cm <- "+ l_ppi + rate_k3y + spread_corp3y"
specs <- list(
  list(lab = "baseline", dat = d0, w = NULL, extra = ""),
  list(lab = "no_daegu", dat = d0 %>% filter(region != "daegu"), w = NULL, extra = ""),
  list(lab = "weighted", dat = d0, w = "w", extra = ""),
  list(lab = "contemp_macro", dat = d0, w = NULL, extra = cm))
res <- bind_rows(lapply(specs, function(s) bind_rows(
  fitset(s$dat, paste(ra, s$extra), FALSE, s$w) %>% mutate(panel = "avg", spec = s$lab),
  fitset(s$dat, paste(rr, s$extra), TRUE, s$w) %>% mutate(panel = "reg", spec = s$lab))))
write.csv(res, "out/est_robust_avg.csv", row.names = FALSE)

# ---------------- table (tabular only)
pv <- function(b, s) 2 * pnorm(-abs(b / s))
stars <- function(p) ifelse(p < .01, "^{***}", ifelse(p < .05, "^{**}", ifelse(p < .1, "^{*}", "")))
num <- function(x, d = 3) { s <- formatC(x, format = "f", digits = d); z <- formatC(0, format = "f", digits = d); ifelse(s == paste0("-", z), z, s) }
comma <- function(n) formatC(n, format = "d", big.mark = "{,}")
sp <- c("baseline", "no_daegu", "weighted", "contemp_macro"); ns <- length(sp)
cell <- function(pn, s, h, what) { x <- res[res$panel == pn & res$spec == s & res$h == h, ]
  if (what == "b") paste0("$", num(x$b), stars(pv(x$b, x$se)), "$") else paste0("$(", num(x$se), ")$") }
row <- function(l, v) paste0(l, " & ", paste(v, collapse = " & "), "\\\\")
t <- c("% structure: rows = horizons by panel, columns = specifications; each cell is a separate LP; generated by n17_robust_avg_costlevel.R",
  sprintf("\\begin{tabular}{@{}l %s@{}}", paste(rep("c", ns), collapse = "")), "\\toprule",
  sprintf("& \\multicolumn{%d}{c}{Cumulative change in log starts; OLS local projections}\\\\", ns),
  sprintf("\\cmidrule(l){2-%d}", ns + 1),
  row("", c("Baseline", "Excluding", "Weighted by", "Same-month")),
  row("", c("", "Daegu", "region size", "macro controls")),
  row("", paste0("(", 1:ns, ")")), "\\midrule",
  sprintf("\\multicolumn{%d}{@{}l}{\\textit{Panel A. Average response, $\\beta_h$}}\\\\[1pt]", ns + 1))
for (h in H) t <- c(t, row(sprintf("\\quad $h=%d$", h), sapply(sp, function(s) cell("avg", s, h, "b"))), row("", sapply(sp, function(s) cell("avg", s, h, "s"))))
t <- c(t, "\\addlinespace[3pt]", sprintf("\\multicolumn{%d}{@{}l}{\\textit{Panel B. Total effect in the high-cost regime, $\\beta_h+\\theta_h$}}\\\\[1pt]", ns + 1))
for (h in H) t <- c(t, row(sprintf("\\quad $h=%d$", h), sapply(sp, function(s) cell("reg", s, h, "b"))), row("", sapply(sp, function(s) cell("reg", s, h, "s"))))
gx <- function(pn, h, col) sapply(sp, function(s) res[res$panel == pn & res$spec == s & res$h == h, col])
t <- c(t, "\\midrule",
  row("\\quad Region fixed effects; lags 1--4 of all variables", rep("Yes", ns)),
  row("\\quad Same-month PPI, Treasury yield and spread", c("No", "No", "No", "Yes")),
  row("\\quad Regions", c("8", "7", "8", "8")),
  row("\\quad Observations ($h=0$)", comma(gx("avg", 0, "n"))),
  row("\\quad Observations ($h=24$)", comma(gx("avg", 24, "n"))),
  row("\\quad $R^2$, Panel A ($h=0$)", num(gx("avg", 0, "r2"))),
  row("\\quad $R^2$, Panel A ($h=24$)", num(gx("avg", 24, "r2"))),
  "\\bottomrule", "\\end{tabular}")
writeLines(t, "tables/tab_t7_robust_avg.tex")

# ---------------- cost level response (national series): log CCI, h = 0..24
nat <- d0 %>% filter(region == "seoul") %>% mutate(region = "nat")
cl <- bind_rows(lapply(0:24, function(h) {
  dd <- nat %>% mutate(y = dplyr::lead(l_cci, h) - l_cci_L1)
  e <- feols(as.formula(paste("y ~ yoy_CCI +", lt(c("yoy_CCI", "l_cci", MX)), "| region")), dd, panel.id = ~ region + tid,
             vcov = DK(lag = h + 1), notes = FALSE, warn = FALSE)
  data.frame(h = h, b = unname(coef(e)["yoy_CCI"]), se = unname(se(e)["yoy_CCI"]), n = nobs(e))
}))
write.csv(cl, "out/est_cost_level.csv", row.names = FALSE)
blue <- "#2a78d6"; ink <- "#0b0b0b"; ink2 <- "#52514e"
p <- ggplot(cl, aes(h, 100 * b)) +
  geom_hline(yintercept = 0, colour = ink2, linewidth = 0.4) +
  geom_ribbon(aes(ymin = 100 * (b - 1.96 * se), ymax = 100 * (b + 1.96 * se)), fill = blue, alpha = 0.16) +
  geom_ribbon(aes(ymin = 100 * (b - 1.645 * se), ymax = 100 * (b + 1.645 * se)), fill = blue, alpha = 0.22) +
  geom_line(colour = blue, linewidth = 0.9) + geom_point(colour = blue, fill = "white", shape = 21, size = 1.8, stroke = 0.9) +
  scale_x_continuous(breaks = seq(0, 24, 3)) +
  labs(x = "Months after the cost-growth surprise (h)", y = "Response of the log cost index (percent)") +
  theme_minimal(base_size = 11) +
  theme(panel.grid.minor = element_blank(), panel.grid.major.x = element_blank(), axis.title = element_text(colour = ink2),
        axis.text = element_text(colour = ink2), plot.background = element_rect(fill = "white", colour = NA))
dev <- if (requireNamespace("ragg", quietly = TRUE)) ragg::agg_png else "png"
tmp <- tempfile(fileext = ".png"); ggsave(tmp, p, width = 6.2, height = 3.6, dpi = 300, device = dev, bg = "white")
stopifnot(file.copy(tmp, "figures/fig_cost_level_response.png", overwrite = TRUE))
st <- function(b, s) { p <- pv(b, s); ifelse(p < .01, "***", ifelse(p < .05, "**", ifelse(p < .1, "*", ""))) }
print(res %>% mutate(lab = sprintf("%.3f%s", b, st(b, se))) %>% select(panel, spec, h, lab) %>% tidyr::pivot_wider(names_from = spec, values_from = lab), n = 40)
cat(sprintf("cost level: %s\n", paste(sprintf("h%d %.4f(%.4f)", cl$h, cl$b, cl$se)[c(1, 4, 7, 13, 16, 19, 22, 25)], collapse = "  ")))
